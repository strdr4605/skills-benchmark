def token_band(tokens):
    for band, limit in enumerate((1000, 3000, 8000, 20000)):
        if tokens < limit:
            return band
    return 4


def cell(row, by):
    rv = row["reviews"].get(by)
    if not rv:
        return ""
    parts = [rv["verdict"] or "pending", f"S{rv['setup']}" if rv["setup"] else "", f"T{rv['tokens']}" if rv["tokens"] else "", rv["depth"]]
    return " ".join(p for p in parts if p)


def link_skill(row):
    return f"[{row['id']}]({row.get('_src', '')})" if row.get("_src") else row["id"]


def header(title, note):
    return f"# {title}\n\n> Generated by `python3 scripts/sb.py build`. {note}\n\n"


def table(cols, rows):
    if not rows:
        return "_None yet._\n"
    out = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    for r in rows:
        out += "| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |\n"
    return out


def as_list(value):
    if not value:
        return []
    return value if isinstance(value, list) else [value]


def one_line(text):
    return re.sub(r"\s+", " ", str(text)).strip()


def clip(text, n):
    return text if len(text) <= n else text[: n - 1] + "…"


def rel(path):
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


