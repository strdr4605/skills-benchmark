def apply_auto_screen(data, rows, repos):
    """Only two rules run without a human: byte-identical blobs, and path rules in screen-rules.csv."""
    applied = 0
    first = {}
    for row in sorted(rows.values(), key=lambda r: r["id"]):
        if row["blob"] in first and not row["screen"]:
            row.update(screen="dup", screen_by="auto", dup_of=first[row["blob"]], reason="same blob")
            applied += 1
        first.setdefault(row["blob"], row["id"])
    alias = {r["repo"]: r["alias"] for r in repos.values()}
    for rule in read_csv(conf(data, "screen-rules.csv")):
        for row in rows.values():
            if not row["screen"] and alias[row["repo"]] == rule["alias"] and fnmatch.fnmatch(row["path"], rule["path_glob"]):
                row.update(screen=rule["screen"], screen_by="auto", reason=rule["reason"])
                applied += 1
    return applied


