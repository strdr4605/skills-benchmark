def assign_ids(items, repos, taken):
    """id = <alias>.<skill dir name> (a SKILL.md at the repo root is <alias>.root); same name twice in one repo adds @<first differing path segment>."""
    groups = {}
    for item in items:
        parts = item["path"].split("/")
        name = parts[-2] if len(parts) > 1 else "root"
        groups.setdefault(f"{repos[item['repo']]['alias']}.{name}", []).append(dict(item, name=name))
    for base, group in groups.items():
        if len(group) == 1 and base not in taken:
            group[0]["id"] = base
            continue
        split = [g["path"].split("/") for g in group]
        index = next(i for i in range(min(map(len, split))) if len({s[i] for s in split}) > 1) if len(group) > 1 else 0
        for g, s in zip(group, split):
            g["id"] = f"{base}@{s[index]}"
    return [g for group in groups.values() for g in group]


