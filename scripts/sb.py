def load_logs(data):
    """Parse the first markdown table of each log/<handle>/<YYYY-MM-DD>.md."""
    out = []
    for path in sorted((data / "log").glob("*/*.md")):
        if not re.match(r"\d{4}-\d{2}-\d{2}\.md$", path.name):
            continue
        for cells in table_rows(path.read_text()):
            if len(cells) < 5 or not cells[0]:
                continue
            out.append({
                "date": path.stem, "by": path.parent.name, "skill": cells[0].strip("` "),
                "depth": cells[1], "minutes": int(cells[2]) if cells[2].isdigit() else 0,
                "next": cells[3], "note": cells[4],
            })
    return out


def table_rows(text):
    rows, seen_header = [], False
    for line in text.splitlines():
        if not line.startswith("|"):
            if seen_header and rows:
                break
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if not seen_header:
            seen_header = True
            continue
        if set("".join(cells)) <= set("-: "):
            continue
        rows.append(cells)
    return rows


def front_matter(text):
    """Flat `key: value` front matter. Values may be [a, b] lists. `# comment` is ignored."""
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end < 0:
        return {}, text
    meta = {}
    for line in text[3:end].splitlines():
        if ":" not in line or line.lstrip().startswith("#"):
            continue
        key, value = line.split(":", 1)
        value = re.sub(r"\s+#.*$", "", value).strip().strip("'\"")
        if value.startswith("[") and value.endswith("]"):
            value = [v.strip().strip("'\"") for v in value[1:-1].split(",") if v.strip()]
        meta[key.strip()] = value
    return meta, text[end + 4:]


def split_sections(body):
    sections, current = {}, None
    for line in body.splitlines():
        if line.startswith("## "):
            current = line[3:].strip().lower()
            sections[current] = ""
        elif current:
            sections[current] += line + "\n"
    return {k: v.strip() for k, v in sections.items()}


