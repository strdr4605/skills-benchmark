#!/usr/bin/env python3
"""skills-benchmark tool. Python 3.9+ standard library only.

Sources of truth (hand-edited):
  catalog/skills.csv          one row per skill: facts, screen, scope
  reviews/<handle>/<id>.md    one benchmark record per reviewer per skill
  log/<handle>/<date>.md      one daily log per reviewer per evening

Everything in tables/ and site/data.json is generated by `build`. Never edit it.

Commands:
  import            add new inventory rows to catalog/skills.csv, apply auto screen rules
  fetch             fill name and description from each SKILL.md at the pinned commit
  pick  --by H      list the next skills for reviewer H (due postponed first)
  day   --by H ID…  open today's log for H and create review stubs
  tokens ID         measure the load size of one skill directory (bytes / 4)
  check             validate all sources (CI runs this on every PR)
  build             write tables/ and site/data.json
"""

import argparse
import csv
import datetime
import fnmatch
import json
import os
import re
import subprocess
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

SCREEN = ["keep", "dup", "variant", "out"]
STAGES_ORDER = ["plan", "design", "build", "test", "deploy", "maintain", "anytime"]
TARGETS = ["work", "personal", "both"]
VERDICTS = ["adopt", "adapt", "merge", "reject"]
REJECT_REASONS = ["duplicate", "overlap", "low-value", "too-costly", "broken", "license", "platform"]
EVIDENCE = ["desk", "work", "personal"]
DEPTHS = ["skim", "desk", "trial"]  # ordered: shallow to deep
LOG_DEPTHS = DEPTHS + ["postponed"]
SKILL_COLUMNS = [
    "id", "repo", "path", "blob", "name", "description",
    "screen", "screen_by", "dup_of", "cluster", "reason",
    "stage", "category", "use_case", "target", "priority", "final",
]
BATCH_PREFIXES = ("screen:", "sweep:")  # log rows for stage 1 and 2 batch work
DAY_MINUTES_WARN = 150
DAY_SKILLS_MAX = 10


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", default=".", help="instance dir with catalog/, reviews/, log/ (default: repo root)")
    sub = parser.add_subparsers(dest="cmd", required=True)

    sub.add_parser("import")
    sub.add_parser("fetch")

    p = sub.add_parser("pick")
    p.add_argument("--by", required=True)
    p.add_argument("-n", type=int, default=10)

    p = sub.add_parser("day")
    p.add_argument("--by", required=True)
    p.add_argument("--date", default=today())
    p.add_argument("ids", nargs="+")

    p = sub.add_parser("tokens")
    p.add_argument("id")

    p = sub.add_parser("check")
    p.add_argument("--changed-by", help="GitHub login of the PR author; enables the ownership rules")
    p.add_argument("--base", default="origin/main", help="git revision to diff against for --changed-by")

    p = sub.add_parser("build")
    p.add_argument("--tables", default=None, help="output dir for markdown tables (default: <data>/tables)")
    p.add_argument("--site", default=None, help="output file for board data (default: site/data.json)")

    args = parser.parse_args()
    data = (ROOT / args.data).resolve()
    commands = {
        "import": cmd_import, "fetch": cmd_fetch, "pick": cmd_pick, "day": cmd_day,
        "tokens": cmd_tokens, "check": cmd_check, "build": cmd_build,
    }
    sys.exit(commands[args.cmd](data, args) or 0)


