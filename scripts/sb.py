def cmd_import(data, args):
    repos = {r["repo"]: r for r in read_csv(conf(data, "repos.csv"))}
    inventory = json.loads((ROOT / "catalog" / "inventory.json").read_text())
    rows = {r["id"]: r for r in load_skills(data)}
    known = {(r["repo"], r["path"]) for r in rows.values()}

    fresh = [x for x in inventory if (x["repo"], x["path"]) not in known]
    missing = sorted({x["repo"] for x in fresh if x["repo"] not in repos})
    if missing:
        print("add these repos to catalog/repos.csv first:", ", ".join(missing))
        return 1

    for item in assign_ids(fresh, repos, set(rows)):
        rows[item["id"]] = blank_row(item)

    applied = apply_auto_screen(data, rows, repos)
    write_skills(data, rows.values())
    print(f"imported {len(fresh)} new rows; auto-screened {applied}; total {len(rows)}")


def cmd_fetch(data, args):
    repos = {r["repo"]: r for r in read_csv(conf(data, "repos.csv"))}
    rows = {r["id"]: r for r in load_skills(data)}
    todo = [r for r in rows.values() if not r["description"]]
    cache = ROOT / ".cache" / "skills"
    cache.mkdir(parents=True, exist_ok=True)

    def one(row):
        target = cache / f"{row['blob']}.md"
        if not target.exists():
            url = f"https://raw.githubusercontent.com/{row['repo']}/{repos[row['repo']]['commit']}/{row['path']}"
            try:
                target.write_bytes(http_get(url))
            except Exception as err:  # network errors must not stop the batch
                return row["id"], str(err)
        meta = front_matter(target.read_text(errors="replace"))[0]
        row["name"] = one_line(meta.get("name") or row["name"])
        row["description"] = one_line(meta.get("description", ""))
        return row["id"], None

    with ThreadPoolExecutor(max_workers=16) as pool:
        failed = [(i, e) for i, e in pool.map(one, todo) if e]
    write_skills(data, rows.values())
    print(f"fetched {len(todo) - len(failed)} of {len(todo)}")
    for skill_id, err in failed:
        print(f"  failed {skill_id}: {err}")


def cmd_pick(data, args):
    state = load_state(data)
    for row in queue(state, args.by)[: args.n]:
        print(f"{row['why']:<14} {row['id']:<50} {row['use_case'][:60]}")


def cmd_day(data, args):
    state = load_state(data)
    if args.by not in state["reviewers"]:
        print(f"unknown reviewer {args.by}; see catalog/reviewers.csv")
        return 1
    unknown = [i for i in args.ids if i not in state["skills"]]
    if unknown:
        print("unknown skill ids:", ", ".join(unknown))
        return 1
    if len(args.ids) > DAY_SKILLS_MAX:
        print(f"pick at most {DAY_SKILLS_MAX} skills per day")
        return 1

    log = data / "log" / args.by / f"{args.date}.md"
    if not log.exists():
        rows = "\n".join(f"| {i} |  |  |  |  |" for i in args.ids)
        text = (ROOT / "templates" / "log.md").read_text()
        text = text.replace("{date}", args.date).replace("{reviewer}", args.by).replace("{rows}", rows)
        log.parent.mkdir(parents=True, exist_ok=True)
        log.write_text(text)
        print("created", rel(log))
    else:
        for added in add_log_rows(log, args.ids):
            print("added row", added)

    template = (ROOT / "templates" / "review.md").read_text()
    for skill_id in args.ids:
        path = data / "reviews" / args.by / f"{skill_id}.md"
        if path.exists():
            continue
        row = state["skills"][skill_id]
        text = template.replace("{skill}", skill_id).replace("{reviewer}", args.by)
        text = text.replace("{source}", source_url(row, state["repos"]))
        text = text.replace("{commit}", state["repos"][row["repo"]]["commit"])
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print("created", rel(path))


def add_log_rows(log, ids):
    """Add a row for every id that has no row yet. Returns the ids added."""
    lines = log.read_text().splitlines()
    present = set()
    for line in lines:
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if cells and cells[0] and cells[0] != "skill":
                present.add(cells[0].strip("` "))
    missing = [i for i in ids if i not in present]
    if not missing:
        return []
    last = max(index for index, line in enumerate(lines) if line.startswith("|"))
    lines[last + 1 : last + 1] = [f"| {i} |  |  |  |  |" for i in missing]
    log.write_text("\n".join(lines) + "\n")
    return missing


def cmd_tokens(data, args):
    state = load_state(data)
    row = state["skills"].get(args.id)
    if not row:
        print("unknown skill id")
        return 1
    commit = state["repos"][row["repo"]]["commit"]
    folder = row["path"].rsplit("/", 1)[0] if "/" in row["path"] else ""
    url = f"https://api.github.com/repos/{row['repo']}/contents/{folder}?ref={commit}"
    entries = json.loads(http_get(url))
    md = [e for e in entries if e["type"] == "file" and e["name"].endswith(".md")]
    skill_md = sum(e["size"] for e in md if e["name"] == "SKILL.md")
    total = sum(e["size"] for e in md)
    print(f"SKILL.md: {skill_md} bytes = ~{skill_md // 4} tokens")
    print(f"all .md in skill dir: {total} bytes = ~{total // 4} tokens ({len(md)} files)")
    print(f"band if only SKILL.md loads: T{token_band(skill_md // 4)}; if all load: T{token_band(total // 4)}")


def cmd_check(data, args):
    state = load_state(data)
    errors, warnings = validate(state)
    if args.changed_by:
        e, w = validate_ownership(data, state, args.changed_by, args.base)
        errors += e
        warnings += w
    for w in warnings:
        print("warning:", w)
    for e in errors:
        print("error:", e)
    print(f"{len(errors)} errors, {len(warnings)} warnings")
    return 1 if errors else 0


def cmd_build(data, args):
    state = load_state(data)
    errors, _ = validate(state)
    if errors:
        print(f"{len(errors)} errors; run `check` first")
        return 1

    tables = Path(args.tables).resolve() if args.tables else data / "tables"
    site = Path(args.site).resolve() if args.site else ROOT / "site" / "data.json"
    files = render_tables(state)
    for name, text in files.items():
        out = tables / name
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
    site.parent.mkdir(parents=True, exist_ok=True)
    site.write_text(json.dumps(board_data(state), indent=1, ensure_ascii=False))
    print(f"wrote {len(files)} tables to {rel(tables)} and board data to {rel(site)}")


# ---------------------------------------------------------------- state

def load_state(data):
    reviewers = {r["handle"]: r for r in read_csv(conf(data, "reviewers.csv"))}
    state = {
        "data": data,
        "project": {r["key"]: r["value"] for r in read_csv(conf(data, "project.csv"))},
        "repos": {r["repo"]: r for r in read_csv(conf(data, "repos.csv"))},
        "reviewers": reviewers,
        "stages": read_csv(conf(data, "stages.csv")),
        "categories": {r["category"]: r for r in read_csv(conf(data, "categories.csv"))},
        "installed": {r["name"]: r for r in read_csv(conf(data, "installed.csv"))},
        "order": read_csv(conf(data, "order.csv")),
        "skills": {r["id"]: r for r in load_skills(data)},
        "reviews": load_reviews(data),
        "logs": load_logs(data),
    }
    derive(state)
    return state


def derive(state):
    """Join skills, reviews and logs. Nothing derived here is stored by hand."""
    for row in state["skills"].values():
        row["passes"] = []
        row["reviews"] = {}
        row["_src"] = source_url(row, state["repos"])
    for entry in sorted(state["logs"], key=lambda e: (e["date"], e["by"])):
        if entry["skill"] in state["skills"]:
            state["skills"][entry["skill"]]["passes"].append(entry)
    for review in state["reviews"]:
        if review["skill"] in state["skills"]:
            state["skills"][review["skill"]]["reviews"][review["by"]] = review

    for row in state["skills"].values():
        for by, review in row["reviews"].items():
            done = [p for p in row["passes"] if p["by"] == by and p["depth"] in DEPTHS]
            review["depth"] = max((p["depth"] for p in done), key=DEPTHS.index, default="")
            review["minutes"] = sum(p["minutes"] for p in row["passes"] if p["by"] == by)
            review["last"] = max((p["date"] for p in done), default="")
        row["verdict"] = consensus(row)
        row["status"] = status(row)


def consensus(row):
    if row["final"]:
        return row["final"]
    verdicts = {r["verdict"] for r in row["reviews"].values() if r["verdict"]}
    if len(verdicts) > 1:
        return "split"
    return verdicts.pop() if verdicts else ""


def status(row):
    if not row["screen"]:
        return "unscreened"
    if row["screen"] != "keep":
        return row["screen"]
    if not (row["stage"] and row["category"]):
        return "screened"
    if row["verdict"]:
        return "reviewed"
    if row["passes"]:
        return "postponed" if row["passes"][-1]["depth"] == "postponed" else "in-review"
    return "scoped"


def queue(state, by):
    """Next skills for one reviewer, in this order:
    0 postponed and due, 1 second opinion on another reviewer's adopt/adapt, 2 untouched by priority, 3 the rest."""
    now = today()
    out = []
    for row in state["skills"].values():
        if row["screen"] != "keep" or not row["stage"]:
            continue
        mine = [p for p in row["passes"] if p["by"] == by]
        review = row["reviews"].get(by)
        if mine and mine[-1]["depth"] == "postponed":
            due = mine[-1]["next"]
            if re.match(r"\d{4}-\d{2}-\d{2}$", due) and due > now:
                continue
            why = f"due:{due}" if re.match(r"\d{4}-", due) else "blocked"
            out.append(dict(row, why=why, rank=(0, due, row["id"])))
        elif not review or not review["verdict"]:
            prio = int(row["priority"] or 9)
            others = {r["verdict"] for h, r in row["reviews"].items() if h != by}
            if others & {"adopt", "adapt"}:
                out.append(dict(row, why="2nd-opinion", rank=(1, prio, row["id"])))
            elif not others - {""}:
                out.append(dict(row, why=f"P{row['priority'] or '-'}", rank=(2, prio, row["id"])))
            else:
                out.append(dict(row, why=f"P{row['priority'] or '-'} seen", rank=(3, prio, row["id"])))
    return sorted(out, key=lambda r: r["rank"])


# ---------------------------------------------------------------- validation

def validate(state):
    errors, warnings = [], []
    skills, cats = state["skills"], state["categories"]
    stages = {s["stage"] for s in state["stages"]}

    for row in skills.values():
        sid = row["id"]
        if row["screen"] and row["screen"] not in SCREEN:
            errors.append(f"skills.csv {sid}: screen '{row['screen']}' not in {SCREEN}")
        if row["screen"] == "dup" and row["dup_of"] not in skills:
            errors.append(f"skills.csv {sid}: dup needs dup_of = an existing id")
        if row["screen"] == "variant" and not row["cluster"]:
            errors.append(f"skills.csv {sid}: variant needs a cluster")
        if row["screen"] == "out" and not row["reason"]:
            errors.append(f"skills.csv {sid}: out needs a reason")
        if row["screen"] and not row["screen_by"]:
            errors.append(f"skills.csv {sid}: screen needs screen_by")
        if row["stage"] and row["stage"] not in stages:
            errors.append(f"skills.csv {sid}: unknown stage '{row['stage']}'")
        if row["category"] and (row["category"] not in cats or cats[row["category"]]["stage"] != row["stage"]):
            errors.append(f"skills.csv {sid}: category '{row['category']}' is not a category of stage '{row['stage']}'")
        if row["target"] and row["target"] not in TARGETS:
            errors.append(f"skills.csv {sid}: target not in {TARGETS}")
        if row["priority"] and row["priority"] not in ("1", "2", "3"):
            errors.append(f"skills.csv {sid}: priority must be 1, 2 or 3")
        if row["final"] and row["final"] not in VERDICTS:
            errors.append(f"skills.csv {sid}: final not in {VERDICTS}")

    for review in state["reviews"]:
        where = f"reviews/{review['by']}/{review['file']}"
        sid = review["skill"]
        if review["by"] not in state["reviewers"]:
            errors.append(f"{where}: directory is not a reviewer handle")
        if review["file"] != f"{sid}.md":
            errors.append(f"{where}: file name must be <skill>.md")
        if sid not in skills:
            errors.append(f"{where}: unknown skill '{sid}'")
            continue
        errors += [f"{where}: {e}" for e in review_errors(review, skills[sid], state)]
        if review["tokens_run"] and not review["tokens_without"]:
            warnings.append(f"{where}: tokens_run without tokens_without; the cost of the same task without the skill is unknown")

    by_day = {}
    for entry in state["logs"]:
        where = f"log/{entry['by']}/{entry['date']}.md"
        by_day.setdefault(where, []).append(entry)
        if entry["skill"].startswith(BATCH_PREFIXES):
            continue  # screening and sweep work: counted in days.md, not tied to one skill
        if entry["skill"] not in skills:
            errors.append(f"{where}: unknown skill '{entry['skill']}'")
        if entry["depth"] not in LOG_DEPTHS:
            errors.append(f"{where}: {entry['skill']} depth must be one of {LOG_DEPTHS}")
        if entry["depth"] == "postponed" and not entry["next"]:
            errors.append(f"{where}: {entry['skill']} postponed needs next (a date or a blocker)")
        if entry["depth"] in DEPTHS and not (state["data"] / "reviews" / entry["by"] / f"{entry['skill']}.md").exists():
            errors.append(f"{where}: {entry['skill']} has a {entry['depth']} pass but no reviews/{entry['by']}/{entry['skill']}.md")
    for where, entries in by_day.items():
        minutes = sum(e["minutes"] for e in entries)
        if minutes > DAY_MINUTES_WARN:
            warnings.append(f"{where}: {minutes} min is more than one evening ({DAY_MINUTES_WARN})")
        count = sum(1 for e in entries if not e["skill"].startswith(BATCH_PREFIXES))
        if count > DAY_SKILLS_MAX:
            warnings.append(f"{where}: {count} skills; the cadence is 1 to {DAY_SKILLS_MAX}")

    return errors, warnings


def review_errors(review, row, state):
    out = []
    verdict = review["verdict"]
    pinned = state["repos"].get(row["repo"], {}).get("commit", "")
    if verdict and not review["source_commit"]:
        out.append("a verdict needs source_commit")
    if verdict and pinned and review["source_commit"] and review["source_commit"] != pinned:
        out.append(f"source_commit {review['source_commit']} is not the pinned commit {pinned}; the verdict is stale")
    if not review["depth"]:
        out.append("no skim/desk/trial pass in any log of this reviewer; set the depth in the log row first")
    for field in ("setup", "tokens"):
        if review[field] and review[field] not in "01234":
            out.append(f"{field} must be 0 to 4")
    if verdict and verdict not in VERDICTS:
        out.append(f"verdict must be one of {VERDICTS} or empty")
    if verdict and (not review["setup"] or not review["tokens"]):
        out.append("a verdict needs setup and tokens")
    if verdict in ("adopt", "adapt") and DEPTHS.index(review["depth"] or "skim") < 1:
        out.append(f"{verdict} needs at least a desk pass")
    if verdict in ("adopt", "adapt") and not review["license"]:
        out.append(f"{verdict} needs license")
    if verdict in ("adopt", "adapt") and not review["use_cases"]:
        out.append(f"{verdict} needs at least one line under ## Use cases")
    if verdict == "adopt" and review["overlaps"]:
        out.append("adopt is not allowed when overlaps is set; use merge or reject")
    if verdict == "merge" and not review["merge_into"]:
        out.append("merge needs merge_into")
    if verdict == "reject" and review["reject_reason"] not in REJECT_REASONS:
        out.append(f"reject needs reject_reason in {REJECT_REASONS}")
    for name in review["overlaps"]:
        if name not in state["installed"]:
            out.append(f"overlaps '{name}' is not in catalog/installed.csv")
    for item in review["evidence"]:
        if item not in EVIDENCE:
            out.append(f"evidence '{item}' not in {EVIDENCE}")
    if review["reviewer"] != review["by"]:
        out.append("reviewer field must match the directory")
    return out


def validate_ownership(data, state, login, base):
    """PR rules: write only your own reviews and logs, never generated files."""
    errors, warnings = [], []
    handle = next((h for h, r in state["reviewers"].items() if r["github"].lstrip("@") == login), None)
    if not handle:
        return [f"GitHub login '{login}' is not in catalog/reviewers.csv"], []
    changed = git(["diff", "--name-only", f"{base}...HEAD"]).split()
    maintainer = state["reviewers"][handle]["role"] == "maintainer"

    for path in changed:
        parts = path.split("/")
        if parts[0] in ("reviews", "log") and len(parts) > 2 and parts[1] != handle:
            errors.append(f"{path}: only {parts[1]} writes here")
        if parts[0] == "tables" or path == "site/data.json":
            errors.append(f"{path}: generated file; the main build writes it")
        if parts[0] in ("templates", "scripts", "site", ".github") and not maintainer:
            warnings.append(f"{path}: framework change; put it in its own PR")

    if "catalog/skills.csv" in changed:
        before = {r["id"]: r for r in csv.DictReader(git(["show", f"{base}:catalog/skills.csv"]).splitlines())}
        for row in state["skills"].values():
            old = before.get(row["id"])
            if old and any(old.get(c, "") != row[c] for c in SKILL_COLUMNS):
                owner = state["repos"][row["repo"]]["screener"]
                if owner != handle:
                    warnings.append(f"skills.csv {row['id']}: row belongs to screener {owner}")
    return errors, warnings


# ---------------------------------------------------------------- tables

def render_tables(state):
    skills = sorted(state["skills"].values(), key=lambda r: r["id"])
    who = list(state["reviewers"])
    files = {"README.md": render_index(state, skills)}

    for repo in state["repos"].values():
        rows = [r for r in skills if r["repo"] == repo["repo"]]
        if rows:
            files[f"screen/{repo['alias']}.md"] = render_screen(repo, rows)

    for stage in state["stages"]:
        rows = [r for r in skills if r["stage"] == stage["stage"] and r["screen"] == "keep"]
        files[f"stages/{stage['stage']}.md"] = render_stage(state, stage, rows, who)

    shortlist = [r for r in skills if r["verdict"] in ("adopt", "adapt")]
    files["shortlist.md"] = header("Shortlist", "Skills with team verdict adopt or adapt.") + table(
        ["skill", "verdict", "stage", "category", "use case"] + who,
        [[link_skill(r), r["verdict"], r["stage"], r["category"], r["use_case"]] + [cell(r, h) for h in who] for r in shortlist],
    )

    files["queue.md"] = header("Queue", "Next work per reviewer. Due postponed skills come first.") + "".join(
        f"\n## {h}\n\n" + table(["why", "skill", "stage", "use case"],
                               [[r["why"], r["id"], r["stage"], r["use_case"]] for r in queue(state, h)[:30]])
        for h in who
    )

    files["clusters.md"] = render_clusters(state, skills)

    splits = [r for r in skills if r["verdict"] == "split"]
    files["splits.md"] = header("Splits", "Reviewers disagree. Talk, then change your own record or set `final`.") + table(
        ["skill"] + who, [[link_skill(r)] + [cell(r, h) for h in who] for r in splits]
    )

    files["days.md"] = render_days(state)
    return files


def render_index(state, skills):
    counts = {}
    for r in skills:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    verdicts = {}
    for r in skills:
        if r["verdict"]:
            verdicts[r["verdict"]] = verdicts.get(r["verdict"], 0) + 1
    funnel = [
        ["inventory", len(skills)],
        ["unscreened", counts.get("unscreened", 0)],
        ["out (stage 1)", counts.get("out", 0)],
        ["dup (stage 1)", counts.get("dup", 0)],
        ["variant (stage 1/2)", counts.get("variant", 0)],
        ["kept, not scoped", counts.get("screened", 0)],
        ["scoped, not started (stage 2)", counts.get("scoped", 0)],
        ["in review / postponed (stage 3)", counts.get("in-review", 0) + counts.get("postponed", 0)],
        ["reviewed (stage 3)", counts.get("reviewed", 0)],
    ]
    by_repo = []
    for repo in state["repos"].values():
        rows = [r for r in skills if r["repo"] == repo["repo"]]
        if rows:
            done = sum(1 for r in rows if r["screen"])
            by_repo.append([f"[{repo['alias']}](screen/{repo['alias']}.md)", repo["repo"], repo["screener"], len(rows), done, len(rows) - done])
    links = (
        "\n- [Shortlist](shortlist.md)\n- [Queue](queue.md)\n- [Clusters and duplicate hints](clusters.md)"
        "\n- [Splits](splits.md)\n- [Days](days.md)\n- Stages: "
        + ", ".join(f"[{s['name']}](stages/{s['stage']}.md)" for s in state["stages"]) + "\n"
    )
    return (
        header("Benchmark tables", "Generated from catalog/skills.csv, reviews/ and log/. Do not edit.")
        + "## Funnel\n\n" + table(["step", "skills"], funnel)
        + "\n## Verdicts\n\n" + table(["verdict", "skills"], sorted(verdicts.items()))
        + "\n## Screening by repo\n\n" + table(["alias", "repo", "screener", "files", "screened", "left"], by_repo)
        + "\n## Views\n" + links
    )


def render_screen(repo, rows):
    """Human rows get a full table. Auto-screened rows collapse to one line each, so 863 rows stay readable."""
    manual = [r for r in rows if r["screen_by"] != "auto"]
    auto = [r for r in rows if r["screen_by"] == "auto"]
    body = table(
        ["id", "screen", "by", "dup_of / cluster", "reason", "stage / category", "description"],
        [[r["id"], r["screen"] or "·", r["screen_by"], r["dup_of"] or r["cluster"], r["reason"],
          "/".join(x for x in (r["stage"], r["category"]) if x), clip(r["description"], 90)] for r in manual],
    )
    if auto:
        body += f"\n<details><summary>{len(auto)} rows screened by rule (catalog/screen-rules.csv or same blob)</summary>\n\n"
        body += "\n".join(f"- {r['id']}: {r['screen']}, {r['dup_of'] or r['reason']}" for r in auto) + "\n\n</details>\n"
    return header(f"Screen: {repo['alias']}", f"{repo['repo']} at `{repo['commit'][:12]}`. Screener: {repo['screener']}. {len(rows)} files, {len(auto)} by rule.") + body


def render_stage(state, stage, rows, who):
    out = header(f"Stage: {stage['name']}", f"{len(rows)} kept skills. Variants are listed under their cluster in clusters.md.")
    if stage["not_covered"]:
        out += f"**Not covered:** {stage['not_covered']}\n\n"
    for cat in (c for c in state["categories"].values() if c["stage"] == stage["stage"]):
        cat_rows = [r for r in rows if r["category"] == cat["category"]]
        if not cat_rows:
            continue
        out += f"## {cat['name']} ({len(cat_rows)})\n\n{cat['blurb']}\n\n"
        out += table(
            ["skill", "cluster", "P", "target", "use case", "team"] + who,
            [[link_skill(r), r["cluster"], r["priority"], r["target"], r["use_case"], r["verdict"] or r["status"]]
             + [cell(r, h) for h in who] for r in cat_rows],
        ) + "\n"
    return out


def render_clusters(state, skills):
    clusters = {}
    for r in skills:
        if r["cluster"]:
            clusters.setdefault(r["cluster"], []).append(r)
    out = header("Clusters", "Same job, different name. One cluster id per job, set by hand in catalog/skills.csv.")
    out += table(
        ["cluster", "members (screen, team verdict)"],
        [[c, "<br>".join(f"{r['id']} ({r['screen']}, {r['verdict'] or '-'})" for r in rows)] for c, rows in sorted(clusters.items())],
    )

    out += "\n## Hints: same name in more than one repo\n\nScript hint only. Confirm by reading, then set `cluster`.\n\n"
    synonyms = {r["term"]: r["same_as"] for r in read_csv(conf(state["data"], "synonyms.csv"))}
    groups = {}
    for r in skills:
        if r["screen"] in ("out", "dup"):
            continue
        base = r["id"].split(".", 1)[1].split("@")[0]
        key = synonyms.get(base, base)
        groups.setdefault(key, []).append(r)
    hints = [[k, "<br>".join(r["id"] + (f" [{r['cluster']}]" if r["cluster"] else "") for r in rows)]
             for k, rows in sorted(groups.items()) if len({r["repo"] for r in rows}) > 1]
    out += table(["name", "candidates"], hints)

    out += "\n## Hints: same name as an installed skill\n\n"
    installed = [[r["id"], synonyms.get(r["id"].split(".", 1)[1], r["id"].split(".", 1)[1])] for r in skills
                 if synonyms.get(r["id"].split(".", 1)[1].split("@")[0], r["id"].split(".", 1)[1].split("@")[0]) in state["installed"]]
    out += table(["skill", "installed"], installed)
    return out


def render_days(state):
    days = {}
    for e in state["logs"]:
        d = days.setdefault((e["date"], e["by"]), {"min": 0, "n": 0, **{k: 0 for k in LOG_DEPTHS}})
